/**
 * Generates onchain/programs/bullxi/src/universe.rs from the game's stock list,
 * so the program enforces the same squad rules as the app.
 *   npm run onchain:gen
 */
import { writeFileSync } from "node:fs";
import { MOCK_STOCKS } from "../../lib/data/mock/stocks";
import { PRICE_BOOK_STOCKS } from "../../lib/onchain/universe";
import { BUDGET, MAX_PER_SECTOR, POSITIONS, SQUAD_QUOTA, XI_LIMITS } from "../../lib/game/rules";

const order = PRICE_BOOK_STOCKS.map(([t]) => MOCK_STOCKS.find((s) => s.ticker === t)!);
const sectors = [...new Set(order.map((s) => s.sector))];
const n = order.length;
const rs = `// Generated by scripts/onchain/gen-universe.ts. Do not edit by hand.
// Index i matches the price book (lib/onchain/universe.ts).

pub const STOCK_COUNT: usize = ${n};
/// Index of SPYx, the benchmark.
pub const BENCHMARK: usize = ${order.findIndex((s) => s.id === "spyx")};
/// Positions: 0 ETF, 1 Blue Chip, 2 Growth, 3 High Risk.
pub const POSITION: [u8; STOCK_COUNT] = [${order.map((s) => POSITIONS.indexOf(s.position)).join(", ")}];
/// Sectors: ${sectors.map((s, i) => `${i} ${s}`).join(", ")}.
pub const SECTOR: [u8; STOCK_COUNT] = [${order.map((s) => sectors.indexOf(s.sector)).join(", ")}];
/// Price in credits x 10 (12.5 credits = 125).
pub const CREDITS_X10: [u16; STOCK_COUNT] = [${order.map((s) => Math.round(s.credits * 10)).join(", ")}];
pub const SECTOR_COUNT: usize = ${sectors.length};

pub const BUDGET_X10: u32 = ${BUDGET * 10};
pub const MAX_PER_SECTOR: u8 = ${MAX_PER_SECTOR};
/// Squad quota per position.
pub const SQUAD_QUOTA: [u8; 4] = [${POSITIONS.map((p) => SQUAD_QUOTA[p]).join(", ")}];
/// Starting XI min and max per position.
pub const XI_MIN: [u8; 4] = [${POSITIONS.map((p) => XI_LIMITS[p].min).join(", ")}];
pub const XI_MAX: [u8; 4] = [${POSITIONS.map((p) => XI_LIMITS[p].max).join(", ")}];
`;
writeFileSync("onchain/programs/bullxi/src/universe.rs", rs);
console.log(`wrote universe.rs: ${n} stocks, ${sectors.length} sectors`);
